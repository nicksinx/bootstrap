def _write_or_print(content: str, output: Optional[Path]) -> None:
    if output is None:
        print(content)
    else:
        _atomic_write(output.resolve(), content)


def index_cli(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Check or write deterministic OKF directory indexes.")
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--check", action="store_true", help="Report index drift without writing (default)")
    modes.add_argument("--write", action="store_true", help="Write generated index blocks atomically")
    parser.add_argument("--root", type=Path, help="Project root containing .okf")
    parser.add_argument("--format", choices=("text", "json"), default="text")
    args = parser.parse_args(argv)
    root = find_project_root(args.root) if args.root else find_project_root()
    plan = plan_indexes(root)
    if args.write and not plan.errors:
        apply_indexes(plan)
    payload = {
        "root": str(plan.root),
        "mode": "write" if args.write else "check",
        "concepts": plan.scanned,
        "indexes": plan.expected,
        "changed": len(plan.changes),
        "paths": [change.relative for change in plan.changes],
        "errors": list(plan.errors),
    }
    if args.format == "json":
        print(json.dumps(payload, indent=2, sort_keys=True))
    else:
        for error in plan.errors:
            print(f"FAIL: {error}")
        for change in plan.changes:
            action = "WRITE" if args.write else "DRIFT"
            print(f"{action}: {change.relative}")
        if not plan.errors:
            state = "wrote" if args.write else "checked"
            print(f"OKF indexes {state}: {plan.expected} index(es), {plan.scanned} concept(s), {len(plan.changes)} change(s)")
    if plan.errors:
        return 2
    return 0 if args.write or not plan.changes else 1


def freshness_cli(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Report OKF stale_after coverage and overdue concepts.")
    parser.add_argument("--root", type=Path, help="Project root containing .okf")
    parser.add_argument("--as-of", default=dt.date.today().isoformat(), help="Evaluation date (YYYY-MM-DD)")
    parser.add_argument("--check", action="store_true", help="Fail when a non-deprecated concept is stale")
    parser.add_argument("--require-deadlines", action="store_true", help="Also fail when active concepts omit stale_after")
    parser.add_argument("--verbose", action="store_true", help="List untracked concepts as well as stale concepts")
    parser.add_argument("--format", choices=("text", "json"), default="text")
    args = parser.parse_args(argv)
    root = find_project_root(args.root) if args.root else find_project_root()
    try:
        report = freshness_report(root, _parse_date(args.as_of, "as-of"))
    except ToolingError as exc:
        print(json.dumps({"error": str(exc)}) if args.format == "json" else f"FAIL: {exc}")
        return 2
    if args.format == "json":
        print(json.dumps(report, indent=2, sort_keys=True))
    else:
        for item in report["items"]:
            show = item["freshness"] == "stale" or (
                item["freshness"] == "untracked" and (args.verbose or args.require_deadlines)
            )
            if show:
                deadline = item["stale_after"] or "not set"
                print(f"{item['freshness'].upper()}: {item['path']} (stale_after: {deadline})")
        summary = report["summary"]
        if summary["untracked"] and not (args.verbose or args.require_deadlines):
            print(f"INFO: {summary['untracked']} concept(s) have no stale_after; use --verbose to list them")
        print(f"OKF freshness as of {report['as_of']}: {summary['current']} current, {summary['stale']} stale, {summary['untracked']} untracked, {summary['deprecated']} deprecated")
    summary = report["summary"]
    failed = (args.check and summary["stale"] > 0) or (
        args.require_deadlines and summary["untracked"] > 0
    )
    return 1 if failed else 0


def visualize_cli(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Export a read-only OKF concept graph.")
    parser.add_argument("--root", type=Path, help="Project root containing .okf")
    parser.add_argument("--as-of", default=dt.date.today().isoformat(), help="Freshness date (YYYY-MM-DD)")
    parser.add_argument("--format", choices=("json", "html"), default="json")
    parser.add_argument("--output", type=Path, help="Write to a file instead of stdout")
    args = parser.parse_args(argv)
    root = find_project_root(args.root) if args.root else find_project_root()
    try:
        report = graph_report(root, _parse_date(args.as_of, "as-of"))
    except ToolingError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 2
    content = (
        json.dumps(report, indent=2, sort_keys=True) + "\n"
        if args.format == "json"
        else graph_html(report)
    )
    _write_or_print(content.rstrip("\n"), args.output)
    if args.output:
        print(f"OKF {args.format} graph wrote {args.output}: {report['summary']['nodes']} nodes, {report['summary']['edges']} edges")
    return 0
