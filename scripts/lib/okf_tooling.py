#!/usr/bin/env python3
"""Deterministic indexes, graph exports, and freshness reports for OKF v0.2."""

from __future__ import annotations

import argparse
import datetime as dt
import html
import json
import os
import posixpath
import re
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional, Sequence

from okf_validation import FrontmatterError, find_project_root, load_frontmatter


INDEX_BEGIN = "<!-- OKF-INDEX:BEGIN -->"
INDEX_END = "<!-- OKF-INDEX:END -->"
MARKDOWN_LINK_RE = re.compile(r"(?<!!)\[([^\]]+)\]\(([^)]+)\)")
HEADING_RE = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)
URL_SCHEMES = ("http://", "https://", "mailto:", "data:")


class ToolingError(ValueError):
    """Raised when deterministic tooling cannot safely process a bundle."""


@dataclass(frozen=True)
class Concept:
    path: Path
    relative: str
    data: dict[str, Any]
    body: str
    title: str
    description: str


@dataclass(frozen=True)
class IndexChange:
    path: Path
    relative: str
    content: str
    existed: bool


@dataclass(frozen=True)
class IndexPlan:
    root: Path
    scanned: int
    expected: int
    changes: tuple[IndexChange, ...]
    errors: tuple[str, ...]


def _single_line(value: Any) -> str:
    return " ".join(str(value or "").split())


def _heading(body: str, fallback: str) -> str:
    match = HEADING_RE.search(body)
    return _single_line(match.group(1) if match else fallback)


def _display_name(path: Path) -> str:
    words = path.name.replace("-", " ").replace("_", " ").split()
    return " ".join(word.upper() if len(word) <= 3 else word.title() for word in words)


def _markdown_label(value: str) -> str:
    return value.replace("[", "(").replace("]", ")")


def _atomic_write(path: Path, content: str, executable: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = path.stat().st_mode if path.exists() else None
    with tempfile.NamedTemporaryFile(
        "w", encoding="utf-8", dir=path.parent, delete=False, newline=""
    ) as handle:
        handle.write(content)
        temp_path = Path(handle.name)
    if mode is not None:
        os.chmod(temp_path, mode)
    elif executable:
        os.chmod(temp_path, 0o755)
    os.replace(temp_path, path)


def load_concepts(root: Path) -> tuple[Concept, ...]:
    root = root.resolve()
    okf = root / ".okf"
    if not okf.is_dir():
        raise ToolingError(f".okf directory not found under {root}")
    concepts = []
    errors = []
    for path in sorted(okf.rglob("*.md")):
        if path.name in {"index.md", "log.md"}:
            continue
        relative = path.relative_to(root).as_posix()
        try:
            data, body = load_frontmatter(path)
        except (FrontmatterError, OSError, UnicodeDecodeError) as exc:
            errors.append(f"{relative}: {exc}")
            continue
        if data is None:
            errors.append(f"{relative}: missing YAML frontmatter")
            continue
        title = _single_line(data.get("title")) or _heading(body, path.stem)
        description = _single_line(data.get("description"))
        concepts.append(Concept(path, relative, data, body, title, description))
    if errors:
        raise ToolingError("cannot load OKF concepts:\n" + "\n".join(errors))
    return tuple(concepts)


def _replace_generated_block(text: str, block: str, prefix: str) -> str:
    has_begin = INDEX_BEGIN in text
    has_end = INDEX_END in text
    if has_begin != has_end:
        raise ToolingError("index contains only one OKF generated-block marker")
    if has_begin:
        start = text.index(INDEX_BEGIN)
        end = text.index(INDEX_END, start) + len(INDEX_END)
        return text[:start] + block + text[end:]
    base = text if text else prefix
    return base.rstrip() + "\n\n" + block + "\n"


def _index_block(
    directory: Path,
    okf: Path,
    direct: list[Concept],
    children: list[Path],
    descendant_counts: dict[Path, int],
    index_paths: dict[Path, Path],
) -> str:
    lines = [
        INDEX_BEGIN,
        "## Generated Concept Index",
        "",
        "Generated by `scripts/okf-index`. Edit content outside this block.",
        "",
    ]
    for concept in direct:
        target = posixpath.relpath(concept.relative.removeprefix(".okf/"), directory.relative_to(okf).as_posix() or ".")
        label = _markdown_label(concept.title)
        suffix = f" - {concept.description}" if concept.description else ""
        lines.append(f"- [{label}]({target}){suffix}")
    for child in children:
        target = posixpath.relpath(
            index_paths[child].relative_to(okf).as_posix(),
            directory.relative_to(okf).as_posix() or ".",
        )
        count = descendant_counts[child]
        noun = "concept" if count == 1 else "concepts"
        lines.append(f"- [{_markdown_label(_display_name(child))}]({target}) - {count} {noun}")
    if not direct and not children:
        lines.append("- No concepts in this directory.")
    lines.append(INDEX_END)
    return "\n".join(lines)


def _directory_index_target(directory: Path) -> tuple[Path, bool]:
    variants = sorted(
        (
            path
            for path in directory.iterdir()
            if path.is_file() and path.name.lower() == "index.md"
        ),
        key=lambda path: path.name,
    )
    exact = next((path for path in variants if path.name == "index.md"), None)
    if exact is not None:
        return exact, True
    if variants:
        # Preserve legacy case-variant landing pages on every filesystem. On a
        # case-insensitive filesystem, creating index.md would overwrite one.
        return variants[0], False
    return directory / "index.md", True


def plan_indexes(root: Path) -> IndexPlan:
    root = root.resolve()
    okf = root / ".okf"
    try:
        concepts = load_concepts(root)
    except ToolingError as exc:
        return IndexPlan(root, 0, 0, (), (str(exc),))

    directories = {okf}
    for concept in concepts:
        parent = concept.path.parent
        while parent != okf:
            directories.add(parent)
            parent = parent.parent
        directories.add(okf)

    descendant_counts = {
        directory: sum(1 for concept in concepts if concept.path.is_relative_to(directory))
        for directory in directories
    }
    try:
        index_targets = {
            directory: _directory_index_target(directory) for directory in directories
        }
    except OSError as exc:
        return IndexPlan(root, len(concepts), 0, (), (f"cannot inspect index paths: {exc}",))
    generated_directories = {
        directory for directory, (_, generated) in index_targets.items() if generated
    }
    index_paths = {directory: target for directory, (target, _) in index_targets.items()}
    changes = []
    errors = []
    for directory in sorted(directories, key=lambda item: item.relative_to(okf).as_posix()):
        if directory not in generated_directories:
            continue
        direct = sorted(
            (concept for concept in concepts if concept.path.parent == directory),
            key=lambda concept: concept.relative,
        )
        children = sorted(
            (child for child in directories if child.parent == directory),
            key=lambda child: child.name,
        )
        path = index_paths[directory]
        existed = path.is_file()
        try:
            current = path.read_text(encoding="utf-8") if existed else ""
            prefix = "" if directory == okf else f"# {_display_name(directory)} Index\n"
            block = _index_block(
                directory, okf, direct, children, descendant_counts, index_paths
            )
            expected = _replace_generated_block(current, block, prefix)
        except (OSError, UnicodeDecodeError, ToolingError) as exc:
            errors.append(f"{path.relative_to(root).as_posix()}: {exc}")
            continue
        if expected != current:
            changes.append(
                IndexChange(path, path.relative_to(root).as_posix(), expected, existed)
            )
    return IndexPlan(
        root,
        len(concepts),
        len(generated_directories),
        tuple(changes),
        tuple(errors),
    )


def apply_indexes(plan: IndexPlan) -> None:
    if plan.errors:
        raise ToolingError("refusing index writes because planning failed")
    for change in plan.changes:
        _atomic_write(change.path, change.content)


def _parse_date(value: str, label: str) -> dt.date:
    try:
        parsed = dt.date.fromisoformat(value)
    except ValueError as exc:
        raise ToolingError(f"{label} must be YYYY-MM-DD: {value}") from exc
    if parsed.isoformat() != value:
        raise ToolingError(f"{label} must be YYYY-MM-DD: {value}")
    return parsed


def _freshness(data: dict[str, Any], as_of: dt.date) -> str:
    if data.get("status") == "deprecated":
        return "deprecated"
    raw = data.get("stale_after")
    if raw is None:
        return "untracked"
    deadline = _parse_date(str(raw), "stale_after")
    return "stale" if as_of > deadline else "current"


def freshness_report(root: Path, as_of: dt.date) -> dict[str, Any]:
    concepts = load_concepts(root)
    items = []
    counts = {key: 0 for key in ("current", "stale", "untracked", "deprecated")}
    for concept in concepts:
        state = _freshness(concept.data, as_of)
        counts[state] += 1
        items.append(
            {
                "path": concept.relative,
                "title": concept.title,
                "type": concept.data.get("type"),
                "status": concept.data.get("status"),
                "stale_after": concept.data.get("stale_after"),
                "freshness": state,
            }
        )
    return {
        "okf_version": "0.2",
        "as_of": as_of.isoformat(),
        "summary": {"total": len(items), "tracked": counts["current"] + counts["stale"], **counts},
        "items": sorted(items, key=lambda item: (item["freshness"], item["path"])),
    }


def _verification(data: dict[str, Any]) -> str:
    status = data.get("verification_status")
    if isinstance(status, str) and status:
        return status
    if data.get("verified"):
        return "verified"
    return "unverified"


def _resolve_link(root: Path, source: Path, raw: str) -> Optional[str]:
    target = raw.strip().split("#", 1)[0].strip()
    if not target or target.startswith(URL_SCHEMES):
        return None
    if target.startswith("<") and target.endswith(">"):
        target = target[1:-1]
    candidate = (
        (source.parent / target).resolve()
        if not target.startswith("/")
        else (root / ".okf" / target.lstrip("/")).resolve()
    )
    try:
        return candidate.relative_to(root).as_posix()
    except ValueError:
        return None


def graph_report(root: Path, as_of: dt.date) -> dict[str, Any]:
    root = root.resolve()
    concepts = load_concepts(root)
    ids = {concept.relative for concept in concepts}
    nodes = []
    for concept in concepts:
        nodes.append(
            {
                "id": concept.relative,
                "title": concept.title,
                "description": concept.description,
                "type": concept.data.get("type", "Unknown"),
                "status": concept.data.get("status"),
                "verification": _verification(concept.data),
                "stale_after": concept.data.get("stale_after"),
                "freshness": _freshness(concept.data, as_of),
            }
        )
    edges = set()
    for concept in concepts:
        for label, raw in MARKDOWN_LINK_RE.findall(concept.body):
            target = _resolve_link(root, concept.path, raw)
            if target in ids:
                edges.add((concept.relative, target, _single_line(label)))
    edge_items = [
        {"source": source, "target": target, "label": label}
        for source, target, label in sorted(edges)
    ]
    return {
        "okf_version": "0.2",
        "as_of": as_of.isoformat(),
        "summary": {"nodes": len(nodes), "edges": len(edge_items)},
        "nodes": sorted(nodes, key=lambda node: node["id"]),
        "edges": edge_items,
    }


